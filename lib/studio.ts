/**
 * Wie kommt man an ein Werk?
 * - buy:      Kauf auf der Website (Carlebach, eigene Verkaufsseite)
 * - order:    auf Anfrage herstellbar ("בירור הזמנה")
 * - interest: nicht im Verkauf, nur Interesse bekunden ("הבעת עניין")
 */
export type Availability = "buy" | "order" | "interest";

export interface WorkItem {
  /** Kennung, die im Formular mitgeschickt wird, z. B. "נ-03" */
  code: string;
  title: string;
  /** Kleine Zeile ueber dem Titel, z. B. "כתובה" */
  kicker?: string;
  image: Pic;
  /** Beschreibung (Papierschnitte) */
  text?: string[];
  /** Masse und Hinweise */
  specs?: string[];
}

export interface Collection {
  slug: string;
  /** Buchstabe aus dem Konzept: א, ב, ג, ד */
  letter: string;
  title: string;
  /** Zusatz nach dem senkrechten Strich, z. B. "דוגמאות לעבודות" */
  subtitle?: string;
  lead: string;
  paras: string[];
  availability: Availability;
  /** Aufforderung unter der Galerie */
  cta: string;
  /** Zusatzhinweis, z. B. "nicht im Verkauf" */
  note?: string;
  items: WorkItem[];
  /** Fuer Carlebach: eigene Verkaufsseite statt Galerie */
  href?: string;
  /** Titelbild der Gruppe auf der Uebersicht */
  cover?: Pic;
}

